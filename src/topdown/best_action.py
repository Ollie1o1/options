SCAN_ETFS: Tuple[str, ...] = ("SPY", "QQQ", "IWM", "TLT", "XLE", "GLD")


@dataclass(frozen=True)
class ActionCard:
    slot: str                  # "TFSA_CORE" | "TFSA_STOCK" | "TAXABLE_OPTIONS"
    account: str               # "TFSA" | "TAXABLE_ONLY"
    evidence_label: str        # "PROVEN" | "PROMISING" | "CLOSED" | "WAIT"
    headline: str              # One-line face-value action (what to buy / hold / avoid)
    prob_text: str             # Backed-up calibrated P(Win) [95% CI, n] · PF · Tail Risk
    why: str                   # Validated driver & key caveat
    tickers: Tuple[str, ...] = ()
    calibrated: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class DteOptionRow:
    bucket_key: str
    bucket_label: str
    dte_min: int
    dte_max: int
    evidence_label: str        # "PROMISING" | "CLOSED" | "UNTESTED"
    ticker: Optional[str]
    expiration: Optional[str]
    dte: Optional[int]
    strikes: str
    credit_mid: Optional[float]
    friction_pct: Optional[float]
    p_win: Optional[float]
    p_win_ci95: Optional[Tuple[float, float]]
    n_backtest: int
    pf: Optional[float]
    mean_roc: Optional[float]
    avg_loss: Optional[float]
    excess_limit: Optional[float]
    why: str
    flags: Tuple[str, ...] = ()
    quote_source: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class BestActionBundle:
    as_of: str
    execution_window: str
    execution_note: str
    actions: List[ActionCard] = field(default_factory=list)
    dte_rows: List[DteOptionRow] = field(default_factory=list)
    implied_calibration_note: str = ""
    evidence_loaded: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "as_of": self.as_of,
            "execution_window": self.execution_window,
            "execution_note": self.execution_note,
            "actions": [a.to_dict() for a in self.actions],
            "dte_rows": [r.to_dict() for r in self.dte_rows],
            "implied_calibration_note": self.implied_calibration_note,
            "evidence_loaded": self.evidence_loaded,
        }


def load_calibrated_evidence(path: str = DEFAULT_EVIDENCE_PATH) -> Optional[Dict[str, Any]]:
    full = repo_path(path)
    if not os.path.exists(full):
        return None
    try:
        with open(full, encoding="utf-8") as fh:
            data = json.load(fh)
        return data if isinstance(data, dict) else None
    except Exception:
        return None


def format_prob_badge(
    p_win: Optional[float],
    ci95: Optional[Sequence[float]],
    n: int,
    *,
    pf: Optional[float] = None,
    avg_loss: Optional[float] = None,
    mean_ret: Optional[float] = None,
    horizon_tag: str = "",
) -> str:
    """Format an honest, backed-up probability string (never a naked % without CI, n & tail risk)."""
    if p_win is None or not math.isfinite(p_win) or n <= 0:
        return "Unproven / no calibrated sample"
    tag = f"{horizon_tag} " if horizon_tag else ""
    ci_s = ""
    if ci95 and len(ci95) == 2 and all(x is not None and math.isfinite(float(x)) for x in ci95):
        ci_s = f" [{float(ci95[0])*100:.0f}–{float(ci95[1])*100:.0f}%, n={n}]"
    else:
        ci_s = f" [n={n}]"
    parts = [f"{tag}P(Win) {p_win*100:.0f}%{ci_s}"]
    if mean_ret is not None and math.isfinite(mean_ret):
        parts.append(f"Avg {mean_ret*100:+.1f}%")
    if pf is not None and math.isfinite(pf):
        parts.append(f"PF {pf:.2f}" if pf < 50 else "PF >50")
    if avg_loss is not None and math.isfinite(avg_loss) and avg_loss < 0:
        parts.append(f"AvgLoss {avg_loss*100:.1f}%")
    return " · ".join(parts)


def _best_archived_spread_for_bucket(
    bucket: Dict[str, Any],
    *,
    chain_db: str,
    spot_map: Dict[str, float],
    exec_flag: Optional[str],
) -> Optional[Dict[str, Any]]:
    """Find cleanest two-sided Bull Put in `chain_archive.db` matching `bucket` DTE window (offline, instant)."""
    full = repo_path(chain_db)
    if not os.path.exists(full):
        return None
    d_lo = int(bucket["dte_lo"])
    d_hi = int(bucket["dte_hi"])
    tgt_dte = int(bucket["target_dte"])
    tgt_delta = float(bucket["target_delta"])
    wing_pct = float(bucket["wing_pct"])

    best: Optional[Tuple[Tuple[int, float], Dict[str, Any]]] = None
    try:
        con = sqlite3.connect(f"file:{full}?mode=ro", uri=True)
        try:
            for sym in SCAN_ETFS:
                spot = spot_map.get(sym)
                if not spot or spot <= 0:
                    continue
                row_d = con.execute(
                    "SELECT MAX(snap_date) FROM chain_snapshots WHERE symbol = ?",
                    (sym,),
                ).fetchone()
                if not row_d or not row_d[0]:
                    continue
                snap_s = str(row_d[0])[:10]
                snap_d = dt.date.fromisoformat(snap_s)
                exps = [
                    str(r[0])[:10]
                    for r in con.execute(
                        "SELECT DISTINCT expiration FROM chain_snapshots WHERE symbol = ? AND snap_date = ?",
                        (sym, snap_s),
                    ).fetchall()
                    if r and r[0]
                ]
                elig = []
                for e in exps:
                    try:
                        dte = (dt.date.fromisoformat(e) - snap_d).days
                    except ValueError:
                        continue
                    if d_lo <= dte <= d_hi:
                        elig.append((abs(dte - tgt_dte), dte, e))
                if not elig:
                    continue
                elig.sort()
                _, chosen_dte, chosen_exp = elig[0]
                puts = con.execute(
                    "SELECT strike, bid, ask, delta FROM chain_snapshots "
                    "WHERE symbol = ? AND snap_date = ? AND expiration = ? AND LOWER(type) = 'put' "
                    "AND bid > 0 AND ask >= bid",
                    (sym, snap_s, chosen_exp),
                ).fetchall()
                if len(puts) < 2:
                    continue
                # Pick short nearest target delta (or moneyness proxy if delta missing)
                short_cands = []
                for k, b, a, dl in puts:
                    kf, bf, af = float(k), float(b), float(a)
                    if kf > spot:
                        continue
                    if dl is not None and math.isfinite(float(dl)):
                        gap = abs(abs(float(dl)) - tgt_delta)
                        if gap <= 0.12:
                            short_cands.append((gap, kf, bf, af))
                    else:
                        # Rough OTM proxy when archived chain omitted delta
                        otm = 1.0 - kf / spot
                        tgt_otm = max(0.01, wing_pct * 0.8)
                        short_cands.append((abs(otm - tgt_otm) + 0.05, kf, bf, af))
                if not short_cands:
                    continue
                short_cands.sort()
                _, ks, sb, sa = short_cands[0]
                tgt_kl = ks - max(1.0, spot * wing_pct)
                long_cands = [
                    (abs(float(k) - tgt_kl), float(k), float(b), float(a))
                    for k, b, a, _ in puts
                    if float(k) < ks
                ]
                if not long_cands:
                    continue
                long_cands.sort()
                _, kl, lb, la = long_cands[0]
                width = ks - kl
                cr_mid = 0.5 * (sb + sa) - 0.5 * (lb + la)
                cr_cross = sb - la
                if width <= 0 or cr_mid <= 0.05 or cr_cross <= 0 or cr_mid >= width:
                    continue
                fric = ((sa - sb) + (la - lb)) / cr_mid
                if fric > 0.30:
                    continue
                flags: List[str] = ["TAXABLE_ONLY", "LIMIT_ONLY"]
                if exec_flag:
                    flags.append(exec_flag)
                tier = OPRA_O1_LIQUIDITY_TIER.get(sym)
                if tier and tier.get("tier") == "TIER_2_WIDE":
                    flags.append("OPRA_WIDE_TIER2")
                if sym == "GLD":
                    flags.append("GLD_OOS_LAGGED_DELTA")
                pen = (1 if sym in ("GLD", "XLE") else 0)
                cand = {
                    "ticker": sym,
                    "expiration": chosen_exp,
                    "dte": chosen_dte,
                    "strikes": f"{ks:g}/{kl:g}P",
                    "credit_mid": round(cr_mid, 2),
                    "friction_pct": round(fric, 4),
                    "flags": tuple(flags),
                    "quote_source": f"archive:{snap_s}",
                }
                score = (pen, fric)
                if best is None or score < best[0]:
                    best = (score, cand)
        finally:
            con.close()
    except sqlite3.Error:
        return None
    return best[1] if best is not None else None


def _best_live_spread_for_bucket(
    bucket: Dict[str, Any],
    *,
    slices_by_sym: Dict[str, Sequence[Any]],
    spot_map: Dict[str, float],
    exec_flag: Optional[str],
) -> Optional[Dict[str, Any]]:
    """Select cleanest live Bull Put for `bucket` from pre-fetched multi-expiry slices."""
    d_lo = int(bucket["dte_lo"])
    d_hi = int(bucket["dte_hi"])
    tgt_dte = int(bucket["target_dte"])
    tgt_delta = float(bucket["target_delta"])
    wing_pct = float(bucket["wing_pct"])

    best: Optional[Tuple[Tuple[int, float], Dict[str, Any]]] = None
    for sym, slices in slices_by_sym.items():
        spot = spot_map.get(sym)
        if not spot or spot <= 0:
            continue
        elig = [s for s in slices if d_lo <= int(s.dte) <= d_hi]
        if not elig:
            continue
        sl = min(elig, key=lambda s: abs(int(s.dte) - tgt_dte))
        sp = sl.match_by_delta("put", tgt_delta, min_bid=0.05)
        if sp is None:
            continue
        lp = sl.match_contract("put", sp.strike - max(1.0, spot * wing_pct), max_rel_dist=0.06, min_bid=0.02)
        if lp is None or lp.strike >= sp.strike:
            continue
        width = sp.strike - lp.strike
        cr_mid = sp.mid - lp.mid
        cr_cross = sp.bid - lp.ask
        if cr_mid <= 0.05 or cr_cross <= 0 or cr_mid >= width:
            continue
        fric = ((sp.ask - sp.bid) + (lp.ask - lp.bid)) / cr_mid
        if fric > 0.30:
            continue
        flags: List[str] = ["TAXABLE_ONLY", "LIMIT_ONLY"]
        if exec_flag:
            flags.append(exec_flag)
        if sym == "GLD":
            flags.append("GLD_OOS_LAGGED_DELTA")
        tier = OPRA_O1_LIQUIDITY_TIER.get(sym)
        if tier and tier.get("tier") == "TIER_2_WIDE":
            flags.append("OPRA_WIDE_TIER2")
        pen = 1 if sym in ("GLD", "XLE") else 0
        cand = {
            "ticker": sym,
            "expiration": sl.expiration,
            "dte": int(sl.dte),
            "strikes": f"{sp.strike:g}/{lp.strike:g}P",
            "credit_mid": round(cr_mid, 2),
            "friction_pct": round(fric, 4),
            "flags": tuple(flags),
            "quote_source": str(sl.source),
        }
        score = (pen, fric)
        if best is None or score < best[0]:
            best = (score, cand)
    return best[1] if best is not None else None


def build_best_action(
    hub: Any,
    *,
    chain_db: str = "data/chain_archive.db",
    evidence_path: str = DEFAULT_EVIDENCE_PATH,
    live_options: bool = False,
    sort_dte_by: str = "dte",  # "dte" (0DTE -> 6M+) | "evidence" (PROMISING first)
    now_et: Optional[dt.datetime] = None,
) -> BestActionBundle:
    """Build the face-value '0 · BEST ACTION TODAY' summary + DTE-sorted options strip."""
    ev = load_calibrated_evidence(evidence_path)
    exec_win = options_execution_window_guidance(now_et=now_et)
    exec_flag = str(exec_win["flag"]) if exec_win.get("flag") else None

    b = hub.board
    spy = hub.macro.spy or {}
    spy_above_200 = spy.get("above_200d")

    actions: List[ActionCard] = []

    # ── 1. TFSA Core Sleeve (PROVEN: VM_OUTLOOK_TOP3) ────────────────────────
    held_rows = [r for r in b.rows if r.weight > 0]
    held_str = " · ".join(f"{r.etf} {r.weight*100:.0f}%" for r in held_rows) or "100% Cash/SGOV"
    cash_pct = (b.sleeve_cash or 0.0) * 100.0
    is_calm = (b.sleeve_scale or 0.0) >= 0.99
    vm_ev = (ev or {}).get("vm_outlook_top3") or {}
    vm_h = vm_ev.get("horizons") or {}
    h3 = vm_h.get("3m_calm" if is_calm else "3m_elevated") or vm_h.get("3m_all") or {}
    h12 = vm_h.get("12m_all") or {}
    vm_cal = bool(vm_ev.get("calibrated"))
    p3_txt = format_prob_badge(
        h3.get("p_win"), h3.get("ci95"), int(h3.get("n") or 0),
        mean_ret=h3.get("mean_ret"), pf=h3.get("pf"), avg_loss=h3.get("avg_loss"), horizon_tag="3m",
    )
    if h12.get("p_win") is not None:
        p3_txt += f" | 12m {float(h12['p_win'])*100:.0f}% (n={int(h12.get('n') or 0)})"
    actions.append(
        ActionCard(
            slot="TFSA_CORE",
            account="TFSA",
            evidence_label="PROVEN",
            headline=f"BUY / HOLD: {held_str} · SGOV {cash_pct:.0f}%",
            prob_text=p3_txt,
            why=(
                f"Only PROVEN sleeve (2006–26 Sharpe 0.82, MaxDD -17.3% vs SPY -55%). "
                f"Basket vol {(b.basket_rv20 or 0)*100:.1f}% ({'CALM' if is_calm else 'ELEVATED'}) · "
                f"Rebalance 10:00–15:55 ET, hold overnight."
            ),
            tickers=tuple(r.etf for r in held_rows),
            calibrated=vm_cal,
        )
    )

    # ── 2. TFSA Stock Satellite (PROMISING: equity_pullback) ─────────────────
    pb_lens = hub.lens("pullbacks")
    clean_pbs = [r for r in (pb_lens.rows if pb_lens else ()) if not r.flags]
    pb_ev = (ev or {}).get("equity_pullback") or {}
    pb_reg = (pb_ev.get("regimes") or {}).get("spy_above_200d" if spy_above_200 is not False else "spy_below_200d") or {}
    pb_txt = format_prob_badge(
        pb_reg.get("p_win"), pb_reg.get("ci95"), int(pb_reg.get("n") or 0),
        mean_ret=pb_reg.get("mean_ret"), pf=pb_reg.get("pf"), avg_loss=pb_reg.get("avg_loss"),
        horizon_tag="3–10d",
    )
    if spy_above_200 is False:
        actions.append(
            ActionCard(
                slot="TFSA_STOCK",
                account="TFSA",
                evidence_label="WAIT",
                headline="WAIT — SPY below 200d (stock pullbacks paused; stay in TFSA Core)",
                prob_text=pb_txt,
                why="Backtest proved uptrend pullbacks lose money in bear markets (2018 & 2022).",
                calibrated=bool(pb_reg.get("n")),
            )
        )
    elif clean_pbs:
        top_pb = clean_pbs[:3]
        actions.append(
            ActionCard(
                slot="TFSA_STOCK",
                account="TFSA",
                evidence_label="PROMISING",
                headline="STOCK PULLBACK (Shares): " + ", ".join(r.ticker for r in top_pb),
                prob_text=pb_txt,
                why="RSI(2)<10 & 3d<=-3% in uptrend (SPY>200d). Exit >SMA5 or 10d. Shares only (fails >10 bps).",
                tickers=tuple(r.ticker for r in top_pb),
                calibrated=bool(pb_reg.get("n")),
            )
        )
    else:
        actions.append(
            ActionCard(
                slot="TFSA_STOCK",
                account="TFSA",
                evidence_label="WAIT",
                headline="NONE TODAY — no clean stock pullbacks (stay in TFSA Core)",
                prob_text=pb_txt,
                why="Discipline edge: sitting in TFSA Core when no clean pullback qualifies beats forcing trades.",
                calibrated=bool(pb_reg.get("n")),
            )
        )

    # ── 3. Options DTE Term-Structure Strip (0DTE -> 240D) ───────────────────
    spot_map: Dict[str, float] = {}
    for sym in SCAN_ETFS:
        tup = (hub.ohlcv or {}).get(sym)
        if tup is not None and len(tup[1]) > 0:
            spot_map[sym] = float(tup[1][-1])

    live_slices_map: Dict[str, Sequence[Any]] = {}
    if live_options:
        from src.structure.chain_data import load_live_chain_slices

        for sym in SCAN_ETFS:
            try:
                sls = load_live_chain_slices(sym, min_dte=0, max_dte=245, max_expirations=6, spot=spot_map.get(sym))
                if sls:
                    live_slices_map[sym] = sls
            except Exception:
                continue

    opt_ev = ((ev or {}).get("options_dte") or {}).get("buckets") or {}
    dte_rows: List[DteOptionRow] = []
    for bcfg in DTE_BUCKETS:
        bkey = str(bcfg["key"])
        bev = opt_ev.get(bkey) or {}
        raw_v = str(bev.get("verdict") or "UNTESTED")
        if raw_v in ("PASS", "LEAD_REFERENCE"):
            ev_label = "PROMISING"
        elif raw_v == "CLOSED":
            ev_label = "CLOSED"
        else:
            ev_label = "UNTESTED"

        cand = (
            _best_live_spread_for_bucket(bcfg, slices_by_sym=live_slices_map, spot_map=spot_map, exec_flag=exec_flag)
            if live_options
            else _best_archived_spread_for_bucket(bcfg, chain_db=chain_db, spot_map=spot_map, exec_flag=exec_flag)
        )

        x_lim = bev.get("excess_entry_limit")
        pf_val = bev.get("pf")
        x_lim_s = f"{float(x_lim)*100:+.2f}%" if x_lim is not None else "n/a"
        if bkey == "60_120D":
            why_s = "Test O1 LEAD (SPY 2010–23 +1.59% @ k=0.35 limit; 2024–26 OOS PF 2.25). Limit orders only."
        elif ev_label == "PROMISING":
            why_s = f"Cleared OPRA 2024–26 delta-adjusted excess ({x_lim_s}) at k=0.35 limit."
        elif ev_label == "CLOSED":
            why_s = (
                f"Backtest CLOSED on OPRA 2024–26 (delta-adj {x_lim_s} @ k=0.35 limit"
                + (f", PF {float(pf_val):.2f}" if pf_val is not None else "")
                + ") — do not chase."
            )
        else:
            why_s = f"{bcfg['horizon']} — run Study 4A/4B to populate empirical verdict."

        ci_raw = bev.get("ci95")
        ci_tup: Optional[Tuple[float, float]] = (
            (float(ci_raw[0]), float(ci_raw[1]))
            if isinstance(ci_raw, list) and len(ci_raw) == 2
            else None
        )
        dte_rows.append(
            DteOptionRow(
                bucket_key=bkey,
                bucket_label=str(bcfg["label"]),
                dte_min=int(bcfg["dte_lo"]),
                dte_max=int(bcfg["dte_hi"]),
                evidence_label=ev_label,
                ticker=cand["ticker"] if cand else None,
                expiration=cand["expiration"] if cand else None,
                dte=cand["dte"] if cand else None,
                strikes=cand["strikes"] if cand else "—",
                credit_mid=cand["credit_mid"] if cand else None,
                friction_pct=cand["friction_pct"] if cand else None,
                p_win=float(bev["p_win"]) if bev.get("p_win") is not None else None,
                p_win_ci95=ci_tup,
                n_backtest=int(bev.get("n") or 0),
                pf=float(pf_val) if pf_val is not None else None,
                mean_roc=float(bev["mean_roc"]) if bev.get("mean_roc") is not None else None,
                avg_loss=float(bev["avg_loss"]) if bev.get("avg_loss") is not None else None,
                excess_limit=float(x_lim) if x_lim is not None else None,
                why=why_s,
                flags=cand["flags"] if cand else ("TAXABLE_ONLY",),
                quote_source=cand["quote_source"] if cand else "",
            )
        )

    if sort_dte_by == "evidence":
        order = {"PROMISING": 0, "UNTESTED": 1, "CLOSED": 2}
        dte_rows.sort(key=lambda r: (order.get(r.evidence_label, 9), r.dte_min))
    else:
        dte_rows.sort(key=lambda r: r.dte_min)

    # Pick the top PROMISING options row (always 60-120D O1 unless another bucket cleared PASS!)
    promising_opts = [r for r in dte_rows if r.evidence_label == "PROMISING"]
    top_opt = promising_opts[0] if promising_opts else None
    if top_opt is not None:
        opt_p_txt = format_prob_badge(
            top_opt.p_win, top_opt.p_win_ci95, top_opt.n_backtest,
            mean_ret=top_opt.mean_roc, pf=top_opt.pf, avg_loss=top_opt.avg_loss,
            horizon_tag=top_opt.bucket_label,
        )
        if top_opt.ticker:
            hl = (
                f"{top_opt.ticker} {top_opt.strikes} exp {top_opt.expiration} ({top_opt.dte}d) · "
                f"Mid ${top_opt.credit_mid:.2f} · Fric {(top_opt.friction_pct or 0)*100:.1f}%"
            )
            tks: Tuple[str, ...] = (top_opt.ticker,)
        else:
            hl = f"Focus strictly on {top_opt.bucket_label} (run `opt radar --live-options` for live NBBO)"
            tks = ("SPY", "QQQ", "TLT")
        actions.append(
            ActionCard(
                slot="TAXABLE_OPTIONS",
                account="TAXABLE_ONLY",
                evidence_label="PROMISING",
                headline=hl,
                prob_text=opt_p_txt,
                why=f"{top_opt.why} Clock: {exec_win['window']} ({exec_win['note']})",
                tickers=tks,
                calibrated=top_opt.n_backtest > 0,
            )
        )

    # C4 implied vs realized summary note
    imp_note = ""
    c4_90 = ((ev or {}).get("implied_vs_realized") or {}).get("90d") or {}
    b25 = c4_90.get("20-30d")
    if isinstance(b25, dict) and b25.get("n"):
        imp_note = (
            f"OPRA 90d 20–30Δ calibration (n={b25['n']}): market implies {float(b25['implied_otm_prob'])*100:.1f}% OTM "
            f"vs {float(b25['realized_otm_prob'])*100:.1f}% realized ({float(b25['vrp_bias_pp']):+.1f} pp VRP)."
        )

    return BestActionBundle(
        as_of=str(b.as_of or ""),
        execution_window=str(exec_win["window"]),
        execution_note=str(exec_win["note"]),
        actions=actions,
        dte_rows=dte_rows,
        implied_calibration_note=imp_note,
        evidence_loaded=ev is not None,
    )


