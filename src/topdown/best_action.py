"""Face-value '0 · BEST ACTION TODAY', DTE-sorted options strip (0DTE -> 6M+), and calibrated probabilities.

Every probability displayed here is loaded from `configs/calibrated_evidence.json`
(generated by `scripts/backtest_probability_calibration.py`, registered in
`docs/PREREG_PROBABILITY_CALIBRATION_20261127.md`).

Hard honesty contract:
  * Never invent or display an uncalibrated Black-Scholes `1 - |delta|` win %.
  * Always pair `P(Win)` with its 95% Wilson CI, sample size `n`, Profit Factor,
    and Avg Loss (tail risk) so high-win-rate / negative-EV traps are unmistakable.
  * Multi-leg options spreads remain strictly `[TAXABLE_ONLY]`.
"""
